"""第五章：星空下的告白 - 比赛之夜，一切水落石出。"""

from text_adventure_romance.engine import display_text, get_choice


def chapter5(state):
    display_text("""
═══════════════════════════════════════
  第五章：星空下的告白
═══════════════════════════════════════

比赛的展览之夜到了。
画廊里灯火通明，人头攒动。

你穿了自己最好的一套衣服来到现场。
入口处的展板上写着：

  「城市温度 —— 青年插画家邀请展」
""")

    display_text("""
你在人群中找到了林悦的作品区。

画的正中央，是那天在公园画的你——
坐在斑驳的光影里，表情安静而温柔。

但她在原画的基础上加了很多东西：
落叶、远处的城市天际线、
一只停在长椅扶手上的小鸟……

画的标题是——「遇见」。

旁边的说明写着：
"献给那些在平凡日子里，
 让世界变得温柔的人。"
""")

    display_text("你在画前站了很久。")

    choice = get_choice([
        "在留言本上写下自己的感受",
        "去找林悦，有些话想当面说",
        "默默看着，等她忙完",
    ])

    state.add_choice(5, choice)

    if choice == 1:
        display_text("""
你在留言本上写道：
"谢谢你让我看到，原来我在一个人眼中可以这么好。
 这幅画很美，但画画的人更美。"

你没有署名，但你知道她一定会认出你的字迹。
""")
        state.modify_affection(10)
        state.set_flag("left_message")

    elif choice == 2:
        display_text("""
你穿过人群去找她。
林悦正在和几个评委交谈，看起来有点紧张。

她看到你的瞬间，整个人都放松了下来。

"你来了。"她说，好像这三个字就是全世界。
"嗯，我来了。"
""")
        state.modify_affection(15)
        state.modify_trust(5)

    else:
        display_text("""
你就站在画旁边，安静地等待。
看着来来往往的人在她的画前驻足。

"这幅画的模特好幸福。"你听到有人说。
你忍不住笑了。

是啊，确实很幸福。
""")
        state.modify_trust(10)

    display_text("""
展览渐渐接近尾声。

主持人宣布了比赛结果——
林悦的「遇见」获得了银奖。

人群中响起掌声。
她走上台领奖，眼眶有些泛红。

"谢谢大家……这幅画对我来说意义非凡。"
她的目光在人群中找到了你。
"因为画里的人，教会了我很多东西。"
""")

    display_text("""
颁奖结束后，人群渐渐散去。
你们一起走出画廊。

秋天的夜晚很凉爽，抬头能看到几颗星星。

"银奖诶，"你说，"恭喜。"

"其实金奖也无所谓啦。"她说，
"最重要的东西，已经得到了。"

她停下脚步，转过身看着你。
月光洒在她身上，像是给她镀了一层银色的光。
""")

    choice2 = get_choice([
        "深呼吸，然后向她告白",
        "牵起她的手，什么都不说",
        "等她先开口",
    ])

    state.add_choice(5, choice2)

    if choice2 == 1:
        display_text(f"""
你深吸一口气。

"林悦。"

"嗯？"

"从第一次在咖啡馆见到你的那天起，
我的生活就开始变得不一样了。"

她安静地听着，月光在她眼中闪烁。

"下雨也好，天晴也好，
只要能见到你，什么天气都是好天气。"

你看着她的眼睛。

"我喜欢你。不是那种'好像有点喜欢'——
是那种每天醒来第一个想到的人就是你的那种喜欢。"

夜风吹过，带着桂花的香气。
她的眼泪掉了下来，但她在笑。
""")
        state.modify_affection(20)
        state.set_flag("confessed")

    elif choice2 == 2:
        display_text("""
你没有说话，只是轻轻地牵起了她的手。

她的手有一点凉，但很快就暖了起来。
她也没有说话，但手指慢慢地扣紧了你的。

有时候，语言是多余的。
十指相扣的温度，已经说明了一切。

走了很久，她终于开口：
"……你的手心好热。"
"因为紧张。"
"我也是。"
""")
        state.modify_affection(15)
        state.modify_trust(10)
        state.set_flag("held_hands")

    else:
        display_text("""
你看着她，没有说话。

她咬了咬嘴唇，脸越来越红。

"你怎么不说话啊……"
"在等你。"
"等我什么？"
"等你想说的话。"

她深吸一口气，然后闭上眼睛——

"我喜欢你！笨蛋！"

她喊完之后自己先捂住了脸。
你笑着轻轻拉下她的手。

"我也是。"
""")
        state.modify_affection(15)
        state.modify_trust(15)
        state.set_flag("she_confessed")

    display_text("—— 第五章 完 ——")
