"""第二章：渐渐靠近 - 在日常相处中，两人的距离悄悄缩短。"""

from text_adventure_romance.engine import display_text, get_choice


def chapter2(state):
    display_text("""
═══════════════════════════════════════
  第二章：渐渐靠近
═══════════════════════════════════════

两周过去了。
""")

    if state.get_flag("got_contact"):
        display_text(f"""
你和林悦开始频繁地聊天。
她会给你发她画的小插画，
你会给她推荐好听的歌。

今天她突然发了一条消息：
"那家咖啡馆新出了樱花拿铁，要不要一起去试试？"
""")
    else:
        display_text(f"""
你开始频繁地光顾那家咖啡馆。
每次去都会不自觉地看向那个角落的位子。

今天你推门进去，发现她正好抬头看向门口。
她冲你招了招手，像是一直在等你来。

"你来啦！新出了樱花拿铁，我帮你也点了一杯。"
""")

    display_text("""
你们在咖啡馆坐了一下午。
她给你看了她最近在画的一组插画——
主题是"城市里的小温柔"。

"这幅是清晨第一缕阳光照进地铁站……"
"这幅是便利店阿姨多给了一块关东煮……"

她一张一张地翻着，眼睛里闪着光。
""")

    choice = get_choice([
        '你的画让我看到了平时注意不到的美好',
        '这幅里的男生背影好像有点像我',
        "安静地听她说，认真看每一幅画",
    ])

    state.add_choice(2, choice)

    if choice == 1:
        display_text("""
她的脸微微泛红。
"真的吗……谢谢。其实很少有人能理解我画的东西。"

她低下头，手指无意识地摩挲着笔记本的边角。
"你是第一个这样说的人。"
""")
        state.modify_affection(10)
        state.modify_trust(5)

    elif choice == 2:
        display_text("""
她的手一抖，差点把咖啡打翻。
"才、才不是你！我画的时候还不认识你呢！"

但她迅速把那一页翻了过去，耳尖红红的。
你忍不住笑了起来。

"别笑了啦！"她小声抗议，但自己也没忍住笑。
""")
        state.modify_affection(15)
        state.set_flag("teased_about_drawing")

    else:
        display_text("""
你一言不发，专注地看着她翻过每一页。
她渐渐不说话了，只是安静地翻着。

两个人之间弥漫着一种温柔的沉默。

"……你知道吗，"她轻声说，
"能和一个人安静地待在一起，是很难得的事。"
""")
        state.modify_trust(15)
        state.modify_affection(5)

    display_text("""
傍晚的时候，你们一起走出咖啡馆。
夕阳把街道染成了金色。

"我……其实最近接了一个很重要的插画比赛。"
她突然说，"但是我一直没找到灵感。"

她转过头看着你，夕阳在她眼中跳跃。
"你愿意当我的模特吗？"
""")

    choice2 = get_choice([
        '我可不上相……但如果你需要的话',
        '当然愿意！什么时候开始？',
        '让我想想……当模特需要做什么？',
    ])

    state.add_choice(2, choice2)

    if choice2 == 1:
        display_text("""
"没关系的，我画的是感觉，不是照片。"
她认真地说，"我觉得你身上有一种……让人安心的气质。"

你的心跳漏了一拍。
"好，那我就勉为其难当一次模特吧。"

她笑了，笑容比夕阳还要灿烂。
""")
        state.modify_affection(5)
        state.modify_trust(10)

    elif choice2 == 2:
        display_text("""
"太好了！"她眼睛一亮，
然后又有些不好意思，"这周末有空吗？
我想去公园写生，你可以在那边……就是坐着就好。"

"没问题，公园见。"

她开心地点了点头，脚步都变得轻快了起来。
""")
        state.modify_affection(10)

    else:
        display_text("""
"就是……你做你自己就好。"
她想了想，"看书、发呆、散步……我来捕捉你自然的样子。"

"听起来不难。"

"嗯！你只要做你自己就是最好的了。"
她说完这句话，自己也愣了一下。

"我是说……画画的时候，自然最好。"她连忙解释。
你笑着点了点头，心里却暖暖的。
""")
        state.modify_trust(10)
        state.modify_affection(5)

    display_text("""
你们约好了周末见面。
回家的路上，你发现自己一直在笑。

手机响了，是她发来的消息：
"今天很开心，谢谢你愿意当我的模特(◕‿◕)"

你打了好几行字又删掉，最后只发了一句：
"我也很开心。"

—— 第二章 完 ——
""")
