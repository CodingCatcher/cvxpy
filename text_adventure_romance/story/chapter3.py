"""第三章：心动的瞬间 - 在公园写生时，感情悄然升温。"""

from text_adventure_romance.engine import display_text, get_choice


def chapter3(state):
    display_text("""
═══════════════════════════════════════
  第三章：心动的瞬间
═══════════════════════════════════════

周末，阳光正好。
你来到约定的公园，林悦已经在长椅上铺好了画具。

她今天穿了一件淡蓝色的连衣裙，
头发用一个小夹子别在耳后。

看到你来，她站起来挥了挥手。
"你来得好早！"
""")

    choice = get_choice([
        '因为有点期待（直球）',
        '我怕你一个人等太久',
        '公园早上空气好，顺便锻炼一下',
    ])

    state.add_choice(3, choice)

    if choice == 1:
        display_text("""
她明显愣了一下，然后别过头去。
"……你这个人怎么突然这样。"

但你看到她的耳朵红了。

"好了好了，快坐好，我要开始画了。"
她假装严肃地拿起了画笔。
""")
        state.modify_affection(15)

    elif choice == 2:
        display_text("""
"我也是刚到！"她笑着说，
但你注意到长椅旁边有一个空了的咖啡杯。

你没有拆穿她其实来了很久的事实。

"那我们开始吧？"你说。
"嗯！"她开心地点头。
""")
        state.modify_trust(10)
        state.modify_affection(5)

    else:
        display_text("""
"锻炼？"她上下打量了你一眼。
"你穿这么好看来锻炼的吗？"

被她一说你才意识到，自己确实比平时穿得用心了些。

"……公园嘛，心旷神怡。"你转移话题。
她偷偷笑了。
""")
        state.modify_affection(5)

    display_text("""
你在长椅上坐下，她在对面支好了画板。
阳光穿过树叶的缝隙，洒下斑驳的光影。

她时而抬头看你，时而低头画画。
每次和你对上目光，就会迅速移开。

"别一直盯着我看……我会画不下去的。"她小声说。
"你不也一直在看我吗？"
"那不一样！我是在观察模特！"

你们都笑了。
""")

    display_text("""
画了一个多小时，她伸了个懒腰。
"休息一下吧，你一定坐累了。"

你走到她身后看画。
画布上的你，坐在光影里，表情安静而温柔。
你不知道自己原来在她眼中是这个样子的。
""")

    choice2 = get_choice([
        '你把我画得太好看了',
        '原来我在你眼里是这样的吗',
        "沉默，但感觉心跳很快",
    ])

    state.add_choice(3, choice2)

    if choice2 == 1:
        display_text("""
"才没有！"她急忙说，"我画的就是你本来的样子！"

说完她自己也意识到这句话的含义，
脸一下子红到了脖子根。

"我、我是说光线好！光线好所以显得好看！"
""")
        state.modify_affection(10)

    elif choice2 == 2:
        display_text("""
她安静了一会儿，然后轻声说：
"……嗯，就是这样的。"

风吹过来，带着花香。
你们站在画布前，肩膀几乎要碰到一起。

谁都没有说话，但空气里满是心跳的声音。
""")
        state.modify_affection(10)
        state.modify_trust(10)

    else:
        display_text("""
你说不出话来，只是静静地看着画。
她也没有说话，只是站在旁边。

过了很久，她开口："……喜欢吗？"

你点了点头。
一个"喜欢"字差点就脱口而出，但你忍住了。
现在还不是时候。
""")
        state.modify_trust(15)

    display_text("""
下午的时候起了风，天空渐渐暗了下来。
远处传来隐约的雷声。

"糟了，要下雨了……"林悦急忙收画具。
你帮她一起收拾，但雨来得比预想中快。

大雨瞬间倾盆而下。
你们抱着画具跑向最近的凉亭。
""")

    display_text("""
你们气喘吁吁地躲进凉亭里。
她的裙子被淋湿了一些，头发上挂着水珠。

她看了看怀里的画板，松了一口气。
"还好……画没有淋到。"

然后她看了看你，突然笑了起来。
"你的头发……好像淋面条。"
"你也好不到哪里去。"

你们在凉亭里笑作一团。
""")

    choice3 = get_choice([
        "把外套脱下来披在她身上",
        "用手帮她擦掉头发上的雨水",
    ])

    state.add_choice(3, choice3)

    if choice3 == 1:
        display_text("""
你脱下外套，轻轻披在她肩上。
"别着凉了。"

她怔了一下，然后把外套裹紧了一些。
"……谢谢。"

她的声音很轻，但在雨声中格外清晰。
她没有看你，但你感觉到她靠近了一点。
""")
        state.modify_affection(10)
        state.modify_trust(10)
        state.set_flag("gave_jacket")

    else:
        display_text("""
你伸手轻轻拂去她发丝上的雨珠。
她呼吸一停，抬起头看着你。

你们之间的距离很近，近到能看见
她睫毛上挂着的细小水珠。

"……"

雷声轰隆隆地响起，她被吓了一跳，
下意识地往你这边靠了靠。

"我不是……我不怕打雷的。"她小声嘟囔。
但她没有移开。
""")
        state.modify_affection(15)
        state.set_flag("touched_hair")

    display_text("""
雨渐渐小了，但谁都没有提要走。
凉亭外的世界被雨水洗得干干净净。

"今天本来是想好好画画的……"她叹了口气，
然后又笑了，"不过，淋雨也挺开心的。"

"下次晴天再来？"

"嗯，一言为定。"

她伸出小指头。你愣了一下，然后勾上了她的手指。

拉勾的瞬间，你觉得整个世界都安静了。

—— 第三章 完 ——
""")
