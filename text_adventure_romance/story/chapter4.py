"""第四章：暴风雨前 - 误会与考验，感情面临危机。"""

from text_adventure_romance.engine import display_text, get_choice


def chapter4(state):
    display_text("""
═══════════════════════════════════════
  第四章：暴风雨前
═══════════════════════════════════════

日子一天天过去，你和林悦越来越亲近。
她的插画比赛作品也接近完成了。

但今天，事情起了变化。
""")

    display_text(f"""
你像往常一样来到咖啡馆，
却看到林悦对面坐着一个男人。

他看起来很体面，穿着得体的西装，
和林悦说话的时候笑容自如。

林悦看到你，表情有些复杂。
"啊，{state.player_name}……这是陈宇，我的……"

"我是林悦的前男友。"那个男人站起来，
对你伸出手，"也是她这次比赛的评委之一。"
""")

    choice = get_choice([
        "礼貌地握手，但心里很不舒服",
        '直接问林悦："你还好吗？"',
        "找借口先离开，给她空间",
    ])

    state.add_choice(4, choice)

    if choice == 1:
        display_text("""
你握了握他的手，力道恰到好处。
"你好。"

陈宇打量了你一眼，笑了笑。
"林悦经常提到你，说你是她的灵感缪斯。"

你看向林悦，她低着头搅拌咖啡，
杯子里的咖啡早就搅匀了。

陈宇很快就告辞了。
""")
        state.modify_trust(5)

    elif choice == 2:
        display_text("""
你没有理会陈宇，直接看向林悦。
"你还好吗？"

林悦抬起头，眼里闪过一丝感动。
"嗯……我没事。"

陈宇沉默了一瞬，然后识趣地站了起来。
"那我先走了，林悦，比赛的事情邮件联系吧。"

他走后，林悦长长地舒了一口气。
""")
        state.modify_affection(10)
        state.modify_trust(10)

    else:
        display_text("""
"你们聊，我就不打扰了。"你转身准备走。

"等一下——"林悦站了起来，碰翻了咖啡杯。
咖啡洒在桌上，她却顾不上收拾。

"你别走，他马上就走了。"她看着你说，
眼神里带着一点慌张，一点恳求。

陈宇若有所思地看了看你们两个。
"那我先告辞了。"他自己提出了离开。
""")
        state.modify_affection(5)
        state.modify_trust(-5)
        state.set_flag("tried_to_leave")

    display_text("""
咖啡馆里只剩下你们两个人。
空气有点沉重。

林悦咬着嘴唇，像是在组织语言。
"他……我们三年前就分手了。
这次比赛我也不知道他是评委。
我怕影响到我的作品，所以才……"

她越说声音越小。
""")

    choice2 = get_choice([
        '你不需要向我解释',
        '我相信你，但我确实有点在意',
        '比赛重要，你专心准备就好',
    ])

    state.add_choice(4, choice2)

    if choice2 == 1:
        display_text("""
"你不需要向我解释，"你平静地说。

她愣了一下。

"但我还是想让你知道——"

"不用。"你打断她，然后笑了笑，
"我在意的从来不是过去，是现在。"

她的眼睛突然红了。
"……你真的这样想吗？"
"嗯。"
""")
        state.modify_trust(15)
        state.modify_affection(10)

    elif choice2 == 2:
        display_text("""
"我相信你。"你认真地说。
"但说不在意是骗人的。"

她安静了很久。
"对不起……我应该早点告诉你的。"

"没关系。以后有什么事，直接跟我说就好。"

她点了点头，伸手握住了你的手。
"好。以后都告诉你。"

你握紧了她的手。
""")
        state.modify_trust(10)
        state.modify_affection(15)
        state.set_flag("honest_about_feelings")

    else:
        display_text("""
"比赛快到了，别想太多，专心准备吧。"

她看着你，眼神有些难过。
"你……是不是生气了？"

"没有。"你说的是实话，也不全是实话。
"我只是希望你能拿到好成绩。"

她低下头。"好……谢谢。"

气氛变得有些疏远。
你心里知道，这不是最好的回答。
""")
        state.modify_trust(-5)
        state.modify_affection(-5)

    display_text("""
接下来的几天，林悦变得很忙。
你们见面的次数少了。

她偶尔会发来消息：
"今天画了一整天，好累。"
"你吃饭了吗？别忘了照顾自己。"

你看着这些消息，想说很多话，
但最后只是回了一个"你也是"。

比赛就要到了。
你知道，不管结果如何，
你们之间的关系都会迎来某种改变。

—— 第四章 完 ——
""")
